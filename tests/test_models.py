def test_the_oracle_scores_perfectly_which_proves_the_harness(holdout):
    """If the oracle does not score 1.0 the scoring code is broken, not the models."""
    result = score(holdout, Oracle().predict(holdout))
    assert result.r2_identity == pytest.approx(1.0)
    assert result.rmse_m == pytest.approx(0.0, abs=1e-12)


def test_the_null_model_explains_nothing_by_construction(train, holdout):
    result = score(holdout, NullModel().fit(train).predict(holdout))
    # A constant predictor cannot explain variance; on a hold-out whose mean differs slightly from
    # the training mean it comes out marginally negative.
    assert -0.05 < result.r2_identity < 0.0
    assert result.rmse_m == pytest.approx(0.1466, abs=5e-4)


def test_every_arm_sits_between_the_null_and_the_oracle(train, holdout):
    """A rung outside those brackets is reporting something other than skill."""
    floor = score(holdout, NullModel().fit(train).predict(holdout)).rmse_m
    for arm in (Kuznetsov(), PublishedRegression(), RefittedRegression().fit(train)):
        result = score(holdout, arm.predict(holdout))
        assert 0.0 < result.rmse_m < floor, f"{arm.name} did not beat a constant predictor"


