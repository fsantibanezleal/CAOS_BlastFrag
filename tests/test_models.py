def test_a_prediction_carries_a_value_or_a_reason_but_never_both(train):
    with pytest.raises(ValueError, match="never both and never neither"):
        Prediction(method="x", blast_id="b", x50_m=0.3, abstain_reason="also a reason")
    with pytest.raises(ValueError, match="never both and never neither"):
        Prediction(method="x", blast_id="b", x50_m=None)


def test_scoring_refuses_a_missing_row_rather_than_dropping_it(train, holdout):
    """A missing cell is not an abstention, and silently averaging it away is the failure mode."""
    predictions = Kuznetsov().predict(holdout)[:-1]
    with pytest.raises(KeyError, match="not the same as an abstention"):
        score(holdout, predictions)


def test_kuz_ram_returns_a_distribution_where_it_returns_a_size(train):
    blast = next(b for b in train if b.blast_id == "Mg1")
    arm = KuzRam()
    prediction = arm.predict_one(blast)
    distribution = arm.distribution(blast)
    assert distribution is not None
    assert distribution.passing_at(prediction.x50_m) == pytest.approx(0.5, abs=1e-4)


def test_swebrec_and_kuz_ram_share_a_mean_and_differ_in_shape(train):
    blast = next(b for b in train if b.blast_id == "Mg1")
    kuzram = KuzRam().distribution(blast)
    swebrec_dist = Swebrec().distribution(blast)
    assert kuzram.x50_m == pytest.approx(swebrec_dist.x50_m, rel=1e-9)
    fine = 0.01
    assert kuzram.passing_at(fine) != pytest.approx(swebrec_dist.passing_at(fine), rel=1e-3)


def test_the_explosive_strength_exponent_default_is_the_form_the_back_solve_selected():
    assert RWS_EXPONENT_DEFAULT == pytest.approx(-19.0 / 30.0)


def test_training_mean_matches_the_corpus(train):
    assert training_mean(train) == pytest.approx(0.3026, abs=5e-4)
