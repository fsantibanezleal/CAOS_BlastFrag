def test_rosin_rammler_passes_half_at_the_mean_size():
    """The 0.693 in the exponent is ln 2, which is what makes x50 the fifty-percent size."""
    distribution = rosin_rammler(0.30, 1.2)
    # The tolerance is the sieve grid: passing_at interpolates linearly in log size between
    # grid points, and the default grid steps by about 4 percent.
    assert distribution.passing_at(0.30) == pytest.approx(0.5, abs=1e-4)
    assert distribution.percentile_m(0.5) == pytest.approx(0.30, rel=1e-3)


def test_rosin_rammler_characteristic_size_passes_sixty_three_percent():
    distribution = rosin_rammler(0.30, 1.2)
    characteristic = distribution.detail["characteristic_size_m"]
    assert distribution.passing_at(characteristic) == pytest.approx(1 - 1 / math.e, abs=1e-4)


def test_swebrec_passes_half_at_the_mean_and_everything_at_the_limit():
    distribution = swebrec(0.30, 2.0, 2.0)
    assert distribution.passing_at(0.30) == pytest.approx(0.5, abs=1e-4)
    assert distribution.passing[-1] == pytest.approx(1.0, abs=1e-9)


def test_swebrec_carries_the_counter_example_that_qualifies_it():
    """The source that recommends it also reports a site where the simpler form fitted better."""
    assert "Babaeian" in swebrec(0.3, 2.0, 2.0).detail["caveat"]


def test_a_higher_uniformity_index_narrows_the_distribution():
    narrow = rosin_rammler(0.30, 2.0)
    wide = rosin_rammler(0.30, 0.8)
    span = lambda d: d.percentile_m(0.9) / d.percentile_m(0.1)  # noqa: E731
    assert span(narrow) < span(wide)


def test_the_crush_zone_composition_adds_fines_and_says_its_constants_are_not_published():
    from blastfrag.classical import CrushZoneParameters, crush_zone

    coarse = rosin_rammler(0.30, 1.2)
    composed = crush_zone(0.30, 1.2, CrushZoneParameters(fines_fraction=0.10))
    fine_mesh = 0.005
    assert composed.passing_at(fine_mesh) > coarse.passing_at(fine_mesh)
    assert composed.detail["constants_are_published"] is False


def test_a_distribution_cannot_decrease_with_size():
    """The type refuses it, so a broken model fails at construction rather than on a chart."""
    from blastfrag.types import SizeDistribution

    with pytest.raises(ValueError, match="must not decrease"):
        SizeDistribution(method="broken", sizes_m=[0.1, 0.2], passing=[0.6, 0.4], x50_m=0.15)


def test_the_sieve_grid_is_shared_and_ascending():
    grid = sieve_grid()
    assert grid == sorted(grid)
    assert rosin_rammler(0.3, 1.2).sizes_m == grid
    assert swebrec(0.3, 2.0, 2.0).sizes_m == grid


