def test_the_classical_equation_reproduces_a_published_prediction(train):
    """Rc1's published classical prediction is 0.72 m, and the rock factor was back-solved from it.

    So this is a round trip rather than an independent check, and it verifies the equation's form,
    its units and the geometry beneath it all at once.
    """
    blast = next(b for b in train if b.blast_id == "Rc1")
    pattern = bf.reconstruct_pattern(blast)
    predicted = kuznetsov_x50_m(pattern, SITE_ROCK_FACTOR["Reocin"])
    assert predicted == pytest.approx(0.72, abs=0.005)


def test_the_back_solved_rock_factor_is_near_constant_within_a_site():
    """The evidence that the geometry reconstruction is right.

    An error in burden or bench height would scatter the recovered factor within a site. It does not:
    the widest spread is 3.7 percent, which is what rounding the published predictions to two
    decimals produces.
    """
    derived = derive_site_rock_factors(column="kuzram_2012")
    multi = {site: v for site, v in derived.items() if v[1] > 1}
    assert len(multi) >= 3, "too few multi-blast sites to make this a check"
    for site, (_mean, _n, spread) in multi.items():
        assert spread < 0.05, f"{site}: the recovered factor scatters by {spread:.1%} within a site"


def test_the_pinned_rock_factors_match_their_derivation():
    """The constants are pinned for reproducibility and regenerated by a function; they must agree."""
    derived = derive_site_rock_factors(column="kuzram_2012")
    assert set(derived) == set(SITE_ROCK_FACTOR)
    for site, factor in SITE_ROCK_FACTOR.items():
        assert factor == pytest.approx(derived[site][0], abs=0.005), site


def test_the_two_published_columns_imply_different_rock_factors():
    """Mixing the two papers' columns is a defect, so the difference is pinned rather than averaged.

    The earlier paper's classical predictions are systematically larger, so the factors recovered
    from it are systematically higher.
    """
    a = derive_site_rock_factors(column="kuzram_2012")
    b = derive_site_rock_factors(column="kuzram_2010")
    shared = set(a) & set(b)
    assert len(shared) >= 7
    higher = sum(1 for site in shared if b[site][0] > a[site][0])
    assert higher == len(shared), "the 2010 column should imply a higher factor at every shared site"


def test_every_recovered_rock_factor_is_inside_the_published_valid_range():
    """The literature states 0.8 to 22. A value outside would say the recovery is wrong."""
    assert all(0.8 <= value <= 22.0 for value in SITE_ROCK_FACTOR.values())


def test_the_recovered_factors_track_rock_stiffness_with_one_inversion(train):
    """Stiffer rock needs a larger factor, and the recovered values broadly show it.

    Measured correlation with Young modulus is 0.87 rather than something near one, and the reason
    is a single inversion worth naming: Enusa is the stiffest rock in the corpus at 60 GPa and its
    recovered factor of 10.97 sits BELOW the Reocin carbonates at 45 GPa. Stiffness is not the only
    thing the rock factor carries, and a folded schist is not a massive carbonate. Pinned rather
    than smoothed, because a monotonic claim here would be false.
    """
    modulus = {b.site: b.E_GPa for b in train}
    pairs = [(modulus[site], factor) for site, factor in SITE_ROCK_FACTOR.items() if site in modulus]
    xs = [p[0] for p in pairs]
    ys = [p[1] for p in pairs]
    mean_x, mean_y = sum(xs) / len(xs), sum(ys) / len(ys)
    cov = sum((x - mean_x) * (y - mean_y) for x, y in pairs)
    r = cov / math.sqrt(
        sum((x - mean_x) ** 2 for x in xs) * sum((y - mean_y) ** 2 for y in ys)
    )
    assert r == pytest.approx(0.87, abs=0.02), f"correlation with modulus is {r:.3f}"
    assert SITE_ROCK_FACTOR["Enusa"] < SITE_ROCK_FACTOR["Reocin"], "the recorded inversion is gone"
    assert modulus["Enusa"] > modulus["Reocin"]


def test_the_uniformity_index_lands_in_its_published_range(train):
    """The source states the index is usually between 0.7 and 2.

    This is the unit trap in the equation: the burden is in metres and the diameter in millimetres,
    so the quotient is around 0.027. Reading it as the corpus's dimensionless ratio, which is a
    thousand times larger, sends the index to about -380. This test is what catches that.
    """
    rows = [b for b in train if bf.has_absolute_geometry(b)]
    patterns = [bf.reconstruct_pattern(b) for b in rows]
    indices = [cunningham_uniformity_index(p) for p in patterns]
    assert len(indices) == 91
    assert all(0.15 < n < 2.0 for n in indices), (min(indices), max(indices))

    # Two thirds sit inside the band the source calls usual. The rest are genuinely unusual blasts
    # rather than a broken equation, and this pins WHY: every index below the band comes from a
    # pattern whose charge column is short relative to its bench, because the stemming eats the
    # hole. The index is linear in that ratio, so a short column is exactly what drives it down.
    inside = [n for n in indices if 0.7 <= n <= 2.0]
    assert len(inside) / len(indices) > 0.65
    for pattern, index in zip(patterns, indices):
        if index < 0.7:
            assert pattern.charge_length_m / pattern.bench_height_m < 0.55


def test_the_2005_uniformity_index_is_defined_on_real_patterns(train):
    values = [
        modified_uniformity_index(bf.reconstruct_pattern(b))
        for b in train
        if bf.has_absolute_geometry(b)
    ]
    assert all(0.3 < n < 2.5 for n in values), (min(values), max(values))


def test_the_classical_arm_abstains_where_the_scale_is_unpublished(train):
    """Six rows, and a number on any of them would be an invention."""
    miami = [b for b in train if b.site == "Miami"]
    predictions = Kuznetsov().predict(miami)
    assert len(predictions) == 6
    assert all(p.abstained for p in predictions)
    assert all("publishes no hole diameter" in (p.abstain_reason or "") for p in predictions)


def test_an_abstention_is_counted_not_averaged_away(train):
    """A missing cell and an abstention are different things and must score differently."""
    miami = [b for b in train if b.site == "Miami"]
    result = score(miami, Kuznetsov().predict(miami))
    assert result.n_scored == 0
    assert result.n_abstained == 6


