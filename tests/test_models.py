def test_the_discriminant_reproduces_every_published_group_membership(train, holdout):
    """Zero errors on all 97 training blasts and all 12 hold-out blasts."""
    for blasts in (train, holdout):
        report = GroupDiscriminant().accuracy(blasts)
        assert report["n_misassigned"] == 0, report["misassigned"]
        assert report["accuracy"] == 1.0


def test_the_two_groups_are_perfectly_separated_by_the_discriminant(train):
    high = [discriminant_score(b) for b in train if b.group == 1]
    low = [discriminant_score(b) for b in train if b.group == 2]
    assert max(low) < min(high), "the groups overlap, so the boundary is not a boundary"
    assert min(high) > DISCRIMINANT_BOUNDARY > max(low)


def test_the_discriminant_abstains_on_size_because_that_is_not_what_it_predicts(train):
    prediction = GroupDiscriminant().predict_one(train[0])
    assert prediction.abstained
    assert prediction.group in (1, 2)


def test_the_published_regression_coefficients_are_not_a_unit_error():
    """The two intercepts differ by a factor of 347 and both return metres.

    That looks wrong and is not: the modulus exponents differ by 0.6 over a range of 9.57 to 60 GPa,
    and the modulus term absorbs the gap. Checked numerically rather than argued.
    """
    from blastfrag.models import PUBLISHED_COEFFICIENTS

    high, low = PUBLISHED_COEFFICIENTS[1], PUBLISHED_COEFFICIENTS[2]
    assert high.intercept / low.intercept == pytest.approx(346.7, rel=0.01)
    # At the boundary of the two groups both equations should return a plausible fragment size.
    for coefficients in (high, low):
        from blastfrag.types import Blast

        probe = Blast(
            blast_id="probe",
            site="probe",
            S_over_B=1.19,
            H_over_B=3.34,
            B_over_D=27.35,
            T_over_B=1.26,
            Pf_kg_m3=0.53,
            XB_m=1.10,
            E_GPa=29.46,
        )
        assert 0.02 < coefficients.predict(probe) < 3.0


def test_the_published_equation_beats_the_numbers_its_own_papers_printed():
    """The finding: applying the published equation correctly outperforms the published table.

    Both source papers print the same two equations. Recomputing them and scoring on the same rows
    gives a materially better result than either paper's own tabulated prediction column, because
    those columns disagree with the equation on several rows.
    """
    arm = PublishedRegression()
    for column, expected_published, expected_ours in (
        ("regression_2010", 0.7467, 0.8537),
        ("regression_2012", 0.7082, 0.8272),
    ):
        rows = [b for b in bf.load_holdout(protocol="union") if b.meta["published"][column] is not None]
        published = score(
            rows,
            [
                Prediction(method="published", blast_id=b.blast_id, x50_m=b.meta["published"][column])
                for b in rows
            ],
        )
        ours = score(rows, arm.predict(rows))
        assert published.r2_identity == pytest.approx(expected_published, abs=5e-4)
        assert ours.r2_identity == pytest.approx(expected_ours, abs=5e-4)
        assert ours.r2_identity > published.r2_identity + 0.10


def test_our_recomputation_agrees_with_the_earlier_paper_where_the_two_disagree():
    """Four rows where the papers differ, and the recomputation lands on the 2010 figure each time."""
    arm = PublishedRegression()
    settled = {"Mr12", "Sm8", "Oz9", "Ad23"}
    for blast in bf.load_holdout(protocol="union"):
        if blast.blast_id not in settled:
            continue
        published = blast.meta["published"]
        ours = round(arm.predict_one(blast).x50_m, 2)
        assert ours == published["regression_2010"], blast.blast_id
        assert ours != published["regression_2012"], blast.blast_id


def test_the_one_row_that_matches_no_published_prediction_is_recorded():
    """Db10: the published equation on its published inputs gives 0.324 m; both papers print 0.16.

    Unresolved, carried with its published inputs. Pinned so it cannot be quietly smoothed away.
    """
    blast = next(b for b in bf.load_holdout(protocol="union") if b.blast_id == "Db10")
    ours = PublishedRegression().predict_one(blast).x50_m
    assert ours == pytest.approx(0.324, abs=0.002)
    assert blast.meta["published"]["regression_2010"] == 0.16
    assert blast.meta["published"]["regression_2012"] == 0.16


def test_refitting_does_not_beat_the_published_coefficients_on_the_holdout(train, holdout):
    """Worth knowing, and slightly against expectation.

    A refit on the same 97 rows generalises marginally WORSE to the published hold-out than the
    coefficients the source authors published, which is a small argument that their fit was not
    overtuned.
    """
    published = score(holdout, PublishedRegression().predict(holdout))
    refitted = score(holdout, RefittedRegression().fit(train).predict(holdout))
    assert refitted.r2_identity < published.r2_identity
    assert refitted.r2_identity > 0.75, "the refit should still be a good model, just not better"


def test_the_refit_refuses_when_a_group_has_too_few_rows(train):
    """Seven exponents from seven rows is interpolation dressed as regression."""
    tiny = [b for b in train if b.group == 1][:5]
    arm = RefittedRegression().fit(tiny)
    prediction = arm.predict_one(train[0])
    assert prediction.abstained
    assert "not contain enough" in (prediction.abstain_reason or "")


